"""Privacy-safe errors crossing the local Python/desktop JSON boundary.

Untrusted OS, media codec and native-library exceptions may contain absolute
paths, URLs, credentials or private script text. Preserve only vetted fixed
messages; never use the original exception text as a generic fallback.
SPDX-License-Identifier: MPL-2.0
"""
from __future__ import annotations

from .inference_errors import describe_model_failure

# These strings are complete KathaSvara-owned messages, not prefixes. Unknown
# text (even if it begins with a known phrase) is never sent to the desktop.
_SAFE_FIXED_MESSAGES = frozenset({
    "Unsupported action.",
    "Enter Hindi story text before generating.",
    "Invalid render job ID.",
    "Assign every unknown speaker manually before rendering.",
    "No speech generated.",
    "No audio was generated.",
    "Speech engine returned invalid or empty audio.",
    "Speech engine returned implausible sample amplitudes.",
    "Inference returned invalid or empty mono samples.",
    "Inference returned implausible sample amplitude.",
    "Render exceeds the 20-minute audio limit.",
    "Choose a new absolute WAV destination.",
    "Refusing to overwrite existing audio.",
    "Speech engine returned effectively silent audio. "
    "Check model weights, hardware and speech generation.",
    "Audio libraries could not initialize. Check Python 3.11, NumPy "
    "and SoundFile compatibility; run the local TTS import probe.",
    "Story audio libraries could not initialize. Check Python 3.11, "
    "NumPy and SoundFile compatibility; run the local TTS import probe.",
})

# Model failure hints are generated by our fixed classifier. Including only
# exact classifier outputs avoids trusting third-party exception strings.
_MODEL_EXAMPLES = (
    MemoryError("out of memory"),
    OSError(28, "No space left on device"),
    RuntimeError("GatedRepoError: access denied"),
    ConnectionError("network is unreachable"),
    ImportError("DLL load failed"),
    RuntimeError("unknown model failure"),
)
_SAFE_MODEL_MESSAGES = frozenset(
    describe_model_failure(example, stage=stage)
    for stage in ("load", "generate")
    for example in _MODEL_EXAMPLES
)


def public_error_message(exc: Exception) -> str:
    """Return only curated help text, never a raw dependency or OS message."""
    message = str(exc)
    if message in _SAFE_FIXED_MESSAGES or message in _SAFE_MODEL_MESSAGES:
        return message
    if isinstance(exc, ImportError):
        return "Speech library import failed. Check the local TTS setup and import probe."
    if isinstance(exc, OSError):
        return "Local file or audio operation failed. Check permissions and available storage."
    if isinstance(exc, (ValueError, TypeError)):
        return "Invalid story, audio or output request. Check the entered settings and paths."
    return (
        "Local speech operation failed. Run TTS diagnostics, "
        "verify the environment and retry."
    )
